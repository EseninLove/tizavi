export function Legal() {
  const { doc: docId } = useParams<{ doc: string }>();
  const navigate = useNavigate();
  const doc = DOCS.find((d) => d.id === docId) ?? DOCS[0];

  return (
    <div className="app-container">
      <header className="px-4 pt-4 pb-2">
        <button
          onClick={() => navigate(-1)}
          className="text-sm text-tg-button font-medium mb-1 active:scale-95 transition-transform"
        >
          ← Назад
        </button>
        <h1 className="text-lg font-bold text-tg-text leading-snug">{doc.header}</h1>
        <p className="text-xs text-tg-hint mt-1">{doc.subtitle}</p>
      </header>

      <main className="scroll-area px-4 pb-4 space-y-4">
        {doc.sections.map((section) => (
          <section key={section.title} className="section-card p-4">
            <h2 className="text-sm font-bold text-tg-text mb-2">{section.title}</h2>
            <div className="space-y-2">
              {section.paragraphs.map((p, i) => (
                <p key={i} className="text-xs text-tg-hint leading-relaxed">
                  {p}
                </p>
              ))}
            </div>
          </section>
        ))}

        <div className="section-card p-4">
          <h2 className="text-sm font-bold text-tg-text mb-2">Другие документы</h2>
          <div className="flex flex-col gap-2">
            {DOCS.filter((d) => d.id !== doc.id).map((d) => (
              <button
                key={d.id}
                onClick={() => navigate(`/legal/${d.id}`)}
                className="w-full flex items-center justify-between px-3 py-2.5 rounded-xl bg-tg-secondary-bg text-left active:scale-[0.98] transition-transform"
              >
                <span className="text-sm text-tg-text">{d.header}</span>
                <span className="text-tg-hint">›</span>
              </button>
            ))}
          </div>
        </div>
      </main>
    </div>
  );
}
