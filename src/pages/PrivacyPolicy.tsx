import { Link } from "react-router-dom";
import { PRIVACY_VERSION, usePrivacyOperator } from "../lib/privacy";
export function PrivacyPolicy() {
  const { operator, error } = usePrivacyOperator();
  const ready = !!(
    operator?.operator_name &&
    operator.inn &&
    operator.address &&
    operator.contact_email &&
    operator.retention &&
    operator.recipients
  );
  const sections = [
    [
      "Где действует политика",
      "Документ относится к интернет-магазину тизави.рф в браузере и Telegram Mini App. Редакция: " +
        PRIVACY_VERSION +
        ". Политика информирует об обработке данных; её просмотр и использование сайта не являются отдельным согласием на любые цели обработки.",
    ],
    [
      "Какие данные используются",
      "Для аккаунта: имя, email и защищённый хеш пароля; при входе через Telegram — идентификатор, имя, username и ссылка на фотографию, если они переданы Telegram. Для заказа: состав покупки, имя, телефон, адрес, комментарий, сведения о доставке и статусе оплаты. Для отзывов: оценка, текст и связь с аккаунтом; текст после проверки виден посетителям, имя и контакты автоматически не публикуются. Для поддержки и запросов по данным: текст обращения, ответ и связь с аккаунтом. Для защиты входа: сессия и технические сведения, в том числе хешированные признаки ограничения попыток входа. Не сообщайте в комментариях паспортные данные, сведения о здоровье и полные реквизиты банковских карт.",
    ],
    [
      "Цели и основания",
      "Аккаунт, оформление покупки, доставка, подписка и связанные обращения обрабатываются в объёме, необходимом для заключения и исполнения договора (п. 5 ч. 1 ст. 6 152-ФЗ). Исполнение установленных законом обязанностей — на соответствующем законном основании. Для иных целей, требующих согласия, необходимо отдельное информированное согласие; эта политика его не заменяет. Рекламные рассылки и необязательная аналитика данным документом не разрешаются.",
    ],
    [
      "Передача и защита",
      "Доступ предоставляется только уполномоченным сотрудникам и необходимым исполнителям. Платёжные реквизиты карты вводятся на странице платёжного сервиса, а не в форме магазина. Подсказки адресов при подключённом геокодировании передаются сервису для поиска адреса. В уведомления Telegram не включаются имена, контакты и тексты обращений или ответов. Telegram как платформа и технические внешние ресурсы могут самостоятельно получать технические данные. Условия локализации и трансграничной передачи должны быть обеспечены оператором отдельно; публикация политики их не подтверждает. Сайт использует HTTPS, серверную проверку доступа и хеширование паролей.",
    ],
    [
      "Хранение в браузере",
      "Сессионная cookie нужна для входа (до 30 дней, прекращается при выходе). Корзина, избранное и тема сохраняются на устройстве. Адрес и черновик оформления используются в пределах вкладки с ограничением 24 часа; адрес дополнительно ограничен сроком расчёта доставки. При выходе адрес и черновик очищаются. Идентификаторы платежей используются для проверки оплаты. Очистить сохранённые данные магазина можно в разделе «Персональные данные». Это не удаляет данные на сервере.",
    ],
    [
      "Права и обращения",
      "Можно запросить сведения об обработке, исправление, прекращение обработки или удаление данных. Для своего аккаунта обращение доступно в разделе «Персональные данные»; ответ публикуется там же. Без входа можно обратиться по указанному ниже контакту оператора. Для защиты данных может потребоваться разумная проверка личности. Отзыв согласия не прекращает обработку, для которой сохраняется иное законное основание. Запрос удаления не означает немедленное уничтожение обязательных документов по покупке. Оператор обязан рассмотреть запрос в применимые сроки и вправе дать мотивированное разъяснение. Пользователь вправе обратиться в Роскомнадзор или суд.",
    ],
  ];
  return (
    <div className="app-container privacy-page">
      <header>
        <Link to="/profile/privacy">← Персональные данные</Link>
        <h1>Политика обработки персональных данных</h1>
        <p>Информация для покупателей</p>
      </header>
      <main className="scroll-area">
        {!ready && (
          <p role="status" className="privacy-warning">
            {error
              ? "Не удалось загрузить сведения об операторе. Попробуйте открыть страницу позднее."
              : !operator
                ? "Загружаем реквизиты оператора…"
                : "Владелец магазина ещё не заполнил все реквизиты и условия хранения. Документ требует завершения оператором и не подтверждает соответствие магазина 152-ФЗ."}
          </p>
        )}
        <section>
          <h2>Оператор персональных данных</h2>
          <p>{operator?.operator_name || "Наименование ещё не указано"}</p>
          <p>ИНН: {operator?.inn || "не указан"}</p>
          <p>Адрес: {operator?.address || "не указан"}</p>
          <p>
            Контакт:{" "}
            {operator?.contact_email ? (
              <a href={`mailto:${operator.contact_email}`}>
                {operator.contact_email}
              </a>
            ) : (
              "ещё не указан владельцем магазина"
            )}
          </p>
        </section>
        {sections.map(([title, text]) => (
          <section key={title}>
            <h2>{title}</h2>
            <p>{text}</p>
          </section>
        ))}
        <section>
          <h2>Получатели данных</h2>
          <p className="whitespace-pre-wrap">
            {operator?.recipients ||
              "Перечень исполнителей и условий передачи оператором ещё не опубликован."}
          </p>
        </section>
        <section>
          <h2>Сроки хранения и порядок уничтожения</h2>
          <p className="whitespace-pre-wrap">
            {operator?.retention ||
              "Сроки по видам данных, основания дальнейшего хранения, порядок уничтожения и работа с резервными копиями должны быть заполнены оператором. Автоматическое удаление серверной истории заказов не выполняется."}
          </p>
        </section>
        <Link className="btn-primary" to="/profile/privacy">
          Мои данные и обращения
        </Link>
      </main>
    </div>
  );
}
